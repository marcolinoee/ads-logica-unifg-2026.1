# Versao while
numero = 1
while numero <= 5:
    print(f"Numero: {numero}")
    numero += 1
# Versao for
for numero in range(1, 6):
    print(f"Numero: {numero}")
# O for e mais legivel pois ja define o intervalo automaticamente
# O while e melhor quando nao sabemos quantas repeticoes serao necessarias
